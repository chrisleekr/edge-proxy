// Generates src/pages/world.ts from Natural Earth's 110m country outlines:
//   node scripts/world.ts <ne_110m_admin_0_countries.geojson> > src/pages/world.ts
// Run from web/admin. The page holds the result, so the browser fetches no map.
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { geoArea } from 'd3-geo';

type Position = number[];
interface Feature {
  properties: { ISO_A2_EH: string; NAME: string; LABEL_X: number; LABEL_Y: number };
  geometry: { type: 'Polygon'; coordinates: Position[][] } | { type: 'MultiPolygon'; coordinates: Position[][][] };
}

const source = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/9380cca83db5f9aef52d5e762765100745f84b27/geojson/ne_110m_admin_0_countries.geojson';
const sha256 = '6866c877d39cba9c357620878839b336d569f8c662d3cfab4cb1dbe2d39c977f';

const round = (v: number) => Math.round(v * 10) / 10 + 0; // + 0 turns -0 into 0

// ring rounds to 0.1 degrees and drops repeated points. A ring left with
// fewer than 4 points (3 distinct and the closing one) is a speck.
function ring(points: Position[]): Position[] | null {
  const out: Position[] = [];
  for (const [x = 0, y = 0] of points) {
    const p: Position = [round(x), round(y)];
    const last = out.at(-1);
    if (!last || last[0] !== p[0] || last[1] !== p[1]) out.push(p);
  }
  return out.length >= 4 ? out : null;
}

// polygon keeps d3's winding: a polygon covering more than a hemisphere is
// wound the wrong way round, and the rings are reversed once to fix it.
function polygon(rings: Position[][]): Position[][] | null {
  const rs = rings.map(ring);
  if (!rs[0]) return null;
  let p = rs.filter((r) => r !== null);
  if (geoArea({ type: 'Polygon', coordinates: p }) > 2 * Math.PI) p = p.map((r) => r.toReversed());
  if (geoArea({ type: 'Polygon', coordinates: p }) > 2 * Math.PI) throw new Error('polygon is not a country-sized area');
  return p;
}

const file = process.argv[2];
if (!file) throw new Error('usage: node scripts/world.ts <geojson>');
// The header names the pinned file, so any other input is refused.
const input = readFileSync(file);
const got = createHash('sha256').update(input).digest('hex');
if (got !== sha256) throw new Error(`${file} has SHA-256 ${got}, want ${sha256} from ${source}`);
const outlines: Record<string, Position[][][]> = {};
const labels: Record<string, [number, number]> = {};
const unnamed: Position[][][] = [];
for (const f of (JSON.parse(input.toString('utf8')) as { features: Feature[] }).features) {
  const { ISO_A2_EH: code, NAME: name, LABEL_X: x, LABEL_Y: y } = f.properties;
  const polys = (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates).map(polygon).filter((p) => p !== null);
  if (polys.length === 0) throw new Error(`${name} has no outline left`);
  if (code === '-99') {
    unnamed.push(...polys);
    continue;
  }
  if (!/^[A-Z0-9]{2}$/.test(code) || code in outlines) throw new Error(`${name}: bad or repeated code ${code}`);
  if (!Number.isFinite(x) || !Number.isFinite(y)) throw new Error(`${name} has no label point`);
  outlines[code] = polys;
  labels[code] = [round(x), round(y)];
}

console.log(`// Generated by scripts/world.ts, do not edit. Natural Earth 110m countries, public domain.
// Source: ${source}
// SHA-256: ${sha256}
// Outlines are polygons of [longitude, latitude] rings in d3-geo's winding, by ISO 3166 alpha-2 code.
// Features with no code (N. Cyprus, Somaliland) are in unnamed and drawn as plain land.
export const outlines: Record<string, number[][][][]> = ${JSON.stringify(outlines)};
export const labels: Record<string, [number, number]> = ${JSON.stringify(labels)};
export const unnamed: number[][][][] = ${JSON.stringify(unnamed)};`);
